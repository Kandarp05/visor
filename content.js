// content.js — main content script orchestrator
// Loaded after feature_extractor/tier2_dom.js (see manifest).
// Responsibilities:
//   document_start → nothing extra (tier2_dom.js already ran)
//   document_idle  → call __visorTier2.run(), expose showInterstitial

(function visorContentMain() {
  'use strict';
  if (location.protocol === 'chrome-extension:') return;

  // Inlined from lib/constants.js (content scripts cannot use ES imports)
  const VISOR_VERSION = '0.1.0';

  console.log('[Visor content] INJECTED document_start', {
    readyState: document.readyState,
    url: location.href,
  });

  // T1.7 ping message
  try {
    chrome.runtime.sendMessage({ type: 'PHASE1_PING' }, () => {
      if (chrome.runtime.lastError) {}
    });
  } catch (e) {}

  // ── Interstitial ────────────────────────────────────────────────────────
  // Called by tier2_dom.js via window.__visorShowInterstitial(verdict).
  // Renders a full-viewport overlay, blocking further interaction.

  function showInterstitial(verdict) {
    // Remove existing if re-triggered
    document.getElementById('__visor_interstitial')?.remove();

    const overlay = document.createElement('div');
    overlay.id = '__visor_interstitial';

    const score = verdict.score != null ? Math.round(verdict.score * 100) : '?';
    const module = verdict.module ?? 'unknown';

    overlay.innerHTML = `
      <div id="__visor_box">
        <div id="__visor_icon">⚠️</div>
        <h1>Potential Phishing Detected</h1>
        <p class="sub">Visor's <strong>${module.toUpperCase()}</strong> detector flagged this page
           (confidence: <strong>${score}%</strong>).</p>
        <div id="__visor_features"></div>
        <div id="__visor_actions">
          <button id="__visor_back">← Go back (safe)</button>
          <button id="__visor_proceed">Proceed anyway</button>
        </div>
        <p class="note">This warning is generated by the Visor browser extension.</p>
      </div>
    `;

    // ── Styles (scoped with id prefix to avoid conflicts) ─────────────────
    const style = document.createElement('style');
    style.textContent = `
      #__visor_interstitial {
        position: fixed; inset: 0; z-index: 2147483647;
        background: rgba(10, 12, 18, 0.97);
        display: flex; align-items: center; justify-content: center;
        font-family: system-ui, -apple-system, sans-serif;
      }
      #__visor_box {
        background: #0f1117; border: 1px solid #ef4444;
        border-radius: 12px; padding: 36px 40px; max-width: 520px;
        width: 90%; text-align: center; color: #e2e8f0;
      }
      #__visor_icon { font-size: 3rem; margin-bottom: 8px; }
      #__visor_box h1 { color: #ef4444; font-size: 1.4rem; margin: 0 0 12px; }
      #__visor_box .sub { color: #94a3b8; font-size: 0.9rem; margin: 0 0 20px; }
      #__visor_box .note { color: #475569; font-size: 0.75rem; margin-top: 16px; }
      #__visor_features {
        background: #1e293b; border-radius: 8px; padding: 12px 16px;
        text-align: left; font-size: 0.8rem; color: #cbd5e1;
        margin-bottom: 20px; min-height: 40px;
      }
      #__visor_actions { display: flex; gap: 12px; justify-content: center; }
      #__visor_back {
        background: #16a34a; color: white; border: none;
        border-radius: 8px; padding: 10px 20px; cursor: pointer;
        font-size: 0.9rem; font-weight: 600;
      }
      #__visor_proceed {
        background: transparent; color: #94a3b8;
        border: 1px solid #334155; border-radius: 8px;
        padding: 10px 20px; cursor: pointer; font-size: 0.9rem;
      }
      #__visor_back:hover    { background: #15803d; }
      #__visor_proceed:hover { border-color: #64748b; color: #e2e8f0; }
    `;
    overlay.prepend(style);

    // Populate top feature flags
    const featuresEl = overlay.querySelector('#__visor_features');
    const pendingVector = window.__visorLastFeatures ?? {};
    const flagged = Object.entries(pendingVector)
      .filter(([, v]) => v === true)
      .map(([k]) => `• ${k.replace(/_/g, ' ')}`);
    featuresEl.innerHTML = flagged.length
      ? '<b>Signals detected:</b><br>' + flagged.join('<br>')
      : 'Feature details unavailable.';

    // Button handlers
    overlay.querySelector('#__visor_back').addEventListener('click', () => {
      history.back();
    });
    overlay.querySelector('#__visor_proceed').addEventListener('click', () => {
      overlay.remove();
      const form = window.__visorPendingForm;
      if (form) {
        window.__visorPendingForm = null;
        form.submit(); // native submit — bypasses JS listeners
      }
    });

    document.documentElement.appendChild(overlay);
  }

  // Expose so tier2_dom.js can call it
  window.__visorShowInterstitial = showInterstitial;

  // ── document_idle: run Tier 2 scan ─────────────────────────────────────

  function onDomReady() {
    console.log('[Visor content] DOM ready, running Tier 2 scan', {
      url: location.href,
      readyState: document.readyState,
    });

    if (typeof window.__visorTier2?.run === 'function') {
      const features = window.__visorTier2.run();
      window.__visorLastFeatures = features; // used by interstitial for display
      console.log('[Visor content] Tier 2 features:', features);
    } else {
      console.warn('[Visor content] __visorTier2 not defined — tier2_dom.js missing?');
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', onDomReady, { once: true });
    window.addEventListener('load', onDomReady, { once: true });
  } else {
    onDomReady();
  }

  // Backup scans for SPAs / dynamic script renders
  setTimeout(onDomReady, 500);
  setTimeout(onDomReady, 1500);

  // Watch for dynamic DOM additions (e.g. login modal or dynamically inserted forms)
  try {
    let debounceTimer = null;
    const observer = new MutationObserver(() => {
      clearTimeout(debounceTimer);
      debounceTimer = setTimeout(onDomReady, 300);
    });
    observer.observe(document.documentElement || document.body, {
      childList: true,
      subtree: true,
    });
  } catch (e) {
    // ignore observer errors if any
  }
})();
